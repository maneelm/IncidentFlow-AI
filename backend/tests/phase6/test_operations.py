def test_container_url_escapes_credentials_and_ignores_host_url(monkeypatch):
    for key, value in {
        "DATABASE_URL": "postgresql+asyncpg://wrong@127.0.0.1:55432/wrong",
        "DB_USER": "local@user",
        "DB_PASSWORD": "private:/@#%value",
        "DB_NAME": "incidentflow",
        "JWT_SECRET": token_urlsafe(48),
        "CORS_ORIGINS": "[]",
        "ENVIRONMENT": "development",
    }.items():
        monkeypatch.setenv(key, value)
    monkeypatch.delenv("CONTAINER_DATABASE_URL", raising=False)
    monkeypatch.delenv("DB_HOST", raising=False)
    settings = database.container_settings()
    url = make_url(str(settings.database_url))
    assert url.host == "postgres" and url.port == 5432
    assert url.username == "local@user" and url.password == "private:/@#%value"
    assert "private" not in repr(settings)


def test_explicit_container_url(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgresql+asyncpg://host@localhost:55432/host")
    monkeypatch.setenv("CONTAINER_DATABASE_URL", "postgresql+asyncpg://custom@db:5432/custom")
    monkeypatch.setenv("JWT_SECRET", token_urlsafe(48))
    assert make_url(str(database.container_settings().database_url)).host == "db"


def test_exec_bootstrap_uses_container_configuration(monkeypatch):
    import os
    import sys

    for key, value in {
        "DATABASE_URL": "postgresql+asyncpg://host@localhost:55432/host",
        "DB_USER": "operator",
        "DB_PASSWORD": "private@value",
        "DB_NAME": "incidentflow",
        "JWT_SECRET": token_urlsafe(48),
    }.items():
        monkeypatch.setenv(key, value)
    monkeypatch.delenv("CONTAINER_DATABASE_URL", raising=False)
    monkeypatch.delenv("DB_HOST", raising=False)
    monkeypatch.setattr(sys, "argv", ["launch", "bootstrap", "--user-role", "admin"])
    monkeypatch.setattr(launch, "configure_logging", lambda: None)

    async def check(settings):
        assert make_url(str(settings.database_url)).host == "postgres"

    commands = []
    monkeypatch.setattr(launch, "check", check)
    monkeypatch.setattr(launch.os, "execv", lambda executable, args: commands.append(args))
    launch.main()
    assert commands == [[sys.executable, "-m", "app.bootstrap", "--role", "admin"]]
    assert make_url(os.environ["DATABASE_URL"]).host == "postgres"


def test_heartbeat_fresh_stale_future_and_invalid(tmp_path: Path):
    path = tmp_path / "heartbeat"
    assert not heartbeat_current(path, now=100)
    for value, expected in [
        ("99", True),
        ("69", False),
        ("101", False),
        ("nan", False),
        ("private garbage", False),
    ]:
        path.write_text(value, encoding="ascii")
        assert heartbeat_current(path, now=100) is expected


async def test_heartbeat_runs_during_idle_and_stops(monkeypatch, tmp_path):
    path = tmp_path / "heartbeat"
    monkeypatch.setenv("WORKER_HEARTBEAT_PATH", str(path))
    ready = asyncio.Event()
    loop = asyncio.get_running_loop()
    original = Path.write_text

    def write_and_notify(target, *args, **kwargs):
        result = original(target, *args, **kwargs)
        loop.call_soon_threadsafe(ready.set)
        return result

    monkeypatch.setattr(Path, "write_text", write_and_notify)
    task = asyncio.create_task(heartbeat_loop())
    async with asyncio.timeout(3):
        await ready.wait()
    assert await asyncio.to_thread(heartbeat_current, path)
    await stop_heartbeat(task)
    assert task.cancelled()


def test_structured_log_omits_exception_payload_and_extras():
    record = logging.LogRecord(
        "ops",
        logging.ERROR,
        "",
        0,
        "startup_failed (%s)",
        ("ValueError",),
        (ValueError, ValueError("password=private"), None),
    )
    record.authorization = "Bearer private"
    output = json.loads(JsonFormatter().format(record))
    assert output["message"] == "startup_failed (ValueError)"
    assert "private" not in json.dumps(output) and "authorization" not in output


@pytest.mark.integration
async def test_migration_is_idempotent_and_preserves_existing_users(sandbox: Sandbox, monkeypatch):
    monkeypatch.setattr(database, "make_engine", lambda _: sandbox.engine)
    for _ in range(2):
        await database.migrate(sandbox.settings)
    async with sandbox.sessions() as session:
        assert set(await session.scalars(select(User.id))) == {
            user.id for user in sandbox.users.values()
        }
    await database.verify_head(sandbox.engine)


@pytest.mark.integration
async def test_migration_gate_rejects_schema_drift(sandbox: Sandbox, monkeypatch):
    monkeypatch.setattr(database, "make_engine", lambda _: sandbox.engine)
    async with sandbox.engine.begin() as connection:
        await connection.execute(text("ALTER TABLE incidents ADD COLUMN deployment_drift text"))
    with pytest.raises(AutogenerateDiffsDetected):
        await database.migrate(sandbox.settings)


@pytest.mark.integration
async def test_startup_rejects_wrong_revision(sandbox: Sandbox):
    async with sandbox.engine.begin() as connection:
        await connection.execute(text("UPDATE alembic_version SET version_num='0003'"))
    with pytest.raises(ValueError, match="migration_revision_mismatch"):
        await database.verify_head(sandbox.engine)
